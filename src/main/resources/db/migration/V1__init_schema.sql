CREATE TABLE instruments
(
    seccode  VARCHAR(32) PRIMARY KEY,
    type     VARCHAR(32)    NOT NULL,
    lot_size BIGINT         NOT NULL CHECK (lot_size > 0),
    min_step NUMERIC(19, 8) NOT NULL CHECK (min_step > 0),
    currency VARCHAR(3)     NOT NULL
);

CREATE TABLE accounts
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL,
    balance          NUMERIC(19, 8) NOT NULL DEFAULT 0,
    reserved_balance NUMERIC(19, 8) NOT NULL DEFAULT 0,
    currency         VARCHAR(3)     NOT NULL,

    CHECK (balance >= 0),
    CHECK (reserved_balance >= 0),
    CHECK (reserved_balance <= balance)
);

CREATE TABLE positions
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT      NOT NULL REFERENCES accounts (id),
    seccode           VARCHAR(32) NOT NULL REFERENCES instruments (seccode),
    quantity          BIGINT      NOT NULL DEFAULT 0,
    reserved_quantity BIGINT      NOT NULL DEFAULT 0,

    UNIQUE (account_id, seccode),

    CHECK (quantity >= 0),
    CHECK (reserved_quantity >= 0),
    CHECK (reserved_quantity <= quantity)
);

CREATE TABLE orders
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT                   NOT NULL REFERENCES accounts (id),
    seccode         VARCHAR(32)              NOT NULL REFERENCES instruments (seccode),
    side            VARCHAR(4)               NOT NULL,
    price           NUMERIC(19, 8)           NOT NULL,
    quantity        BIGINT                   NOT NULL,
    filled_quantity BIGINT                   NOT NULL DEFAULT 0,
    status          VARCHAR(32)              NOT NULL DEFAULT 'NEW',
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CHECK (side IN ('BUY', 'SELL')),
    CHECK (status IN (
                      'NEW',
                      'PARTIALLY_FILLED',
                      'FILLED',
                      'CANCELLED'
        )),
    CHECK (price > 0),
    CHECK (quantity > 0),
    CHECK (filled_quantity >= 0),
    CHECK (filled_quantity <= quantity)
);

CREATE TABLE trades
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccode       VARCHAR(32)              NOT NULL REFERENCES instruments (seccode),
    buy_order_id  BIGINT                   NOT NULL REFERENCES orders (id),
    sell_order_id BIGINT                   NOT NULL REFERENCES orders (id),
    price         NUMERIC(19, 8)           NOT NULL,
    quantity      BIGINT                   NOT NULL,
    executed_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CHECK (price > 0),
    CHECK (quantity > 0),
    CHECK (buy_order_id <> sell_order_id)
);

CREATE INDEX idx_orders_buy_matching
    ON orders (seccode, price DESC, created_at ASC, id ASC) WHERE side = 'BUY'
        AND status IN ('NEW', 'PARTIALLY_FILLED');

CREATE INDEX idx_orders_sell_matching
    ON orders (seccode, price ASC, created_at ASC, id ASC) WHERE side = 'SELL'
        AND status IN ('NEW', 'PARTIALLY_FILLED');

CREATE INDEX idx_orders_account
    ON orders (account_id);

CREATE INDEX idx_trades_instrument
    ON trades (seccode, executed_at DESC);